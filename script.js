function setupRevealAnimations() {
  const revealItems = document.querySelectorAll(".reveal");
  if (!revealItems.length) {
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.14
    }
  );

  revealItems.forEach((item) => observer.observe(item));
}

function setupParallax() {
  const parallaxItems = document.querySelectorAll("[data-depth]");
  if (!parallaxItems.length) {
    return;
  }

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return;
  }

  window.addEventListener("scroll", () => {
    const scrollTop = window.scrollY;
    parallaxItems.forEach((item) => {
      const depth = Number(item.dataset.depth) || 0;
      item.style.transform = `translate3d(0, ${scrollTop * depth}px, 0)`;
    });
  });
}

function setupLanguageToggle() {
  const toggle = document.getElementById("language-toggle");
  if (!toggle) {
    return;
  }

  toggle.addEventListener("click", () => {
    const nextLocale = state.locale === "zh" ? "en" : "zh";
    applyLocale(nextLocale);
  });
}

function setupLightbox() {
  const lightbox = document.getElementById("lightbox");
  const lightboxImage = document.getElementById("lightbox-image");
  const closeButton = document.getElementById("lightbox-close");

  if (!lightbox || !lightboxImage || !closeButton) {
    return;
  }

  document.addEventListener("click", (event) => {
    const trigger = event.target.closest(".photo-zoom-trigger");
    if (trigger) {
      lightboxImage.src = trigger.dataset.fullImage || "";
      lightboxImage.alt = trigger.dataset.fullAlt || "";
      lightbox.hidden = false;
      document.body.classList.add("lightbox-open");
      return;
    }

    if (event.target === lightbox || event.target === closeButton) {
      lightbox.hidden = true;
      lightboxImage.src = "";
      lightboxImage.alt = "";
      document.body.classList.remove("lightbox-open");
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && !lightbox.hidden) {
      lightbox.hidden = true;
      lightboxImage.src = "";
      lightboxImage.alt = "";
      document.body.classList.remove("lightbox-open");
    }
  });
}

